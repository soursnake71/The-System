// Writes plugins/twelve/Params.inc and Presets.inc from engine.js so the plugin has the app's exact parameters and presets.
// Run: node twelve/tools/gen.mjs
import {createRequire} from 'module';
import fs from 'fs';
import path from 'path';
const here = path.dirname(new URL(import.meta.url).pathname), TW = createRequire(import.meta.url)('../engine.js');
const out = path.join(here, '../../plugins/twelve');
const q = s => JSON.stringify(s), num = v => Number.isInteger(v) ? v.toFixed(1) : String(v);
let p = '// generated by twelve/tools/gen.mjs from twelve/engine.js; do not edit\n';
p += 'namespace pid { enum : int { ' + TW.PARAMS.map(x => x.id).join(', ') + ', count }; }\n';
p += `static constexpr int kSound = ${TW.SOUND_IDS.length};\n`;
p += 'static const ParamInfo PARAMS[] = {\n' + TW.PARAMS.map(x => `  {${q(x.id)}, ${q(x.name)}, ${num(x.min)}, ${num(x.max)}, ${num(x.def)}, ${num(x.step)}, ${q(x.unit)}, ${q(x.group)}, ${x.log ? 'true' : 'false'}, ${x.toggle ? 'true' : 'false'}, {${(x.choices || []).map(q).join(', ')}}}`).join(',\n') + '\n};\n';
fs.writeFileSync(path.join(out, 'Params.inc'), p);
const pr = TW.makePresets();
let s = '// generated by twelve/tools/gen.mjs from twelve/engine.js; do not edit\n// name, family, then values in SOUND_IDS order: ' + TW.SOUND_IDS.join(' ') + '\n';
s += 'static const int SOUND_IDS[] = {' + TW.SOUND_IDS.map(id => 'pid::' + id).join(', ') + '};\n';
s += 'static const PresetInfo PRESETS[] = {\n' + pr.map(x => `  {${q(x.name)}, ${q(x.family)}, {${TW.SOUND_IDS.map(id => num(x.values[id])).join(', ')}}}`).join(',\n') + '\n};\n';
fs.writeFileSync(path.join(out, 'Presets.inc'), s);
console.log(`${TW.PARAMS.length} params, ${pr.length} presets, ${TW.SOUND_IDS.length} sound values each`);
