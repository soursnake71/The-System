// Generates plugins/eight/Presets.inc from eight/presets.js: the app's kits and banks as the plugin's programs.
// Each entry is a name and a JSON string ({params, bank, tempo, swing}) read by the plugin with juce::JSON.
// node eight/tools/gen-plugin-presets.mjs
import {createRequire} from 'module';
import {writeFileSync} from 'fs';
import {fileURLToPath} from 'url';
import path from 'path';
const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const P = require('../presets.js');
const kits = P.EIGHT_KITS || globalThis.EIGHT_KITS, banks = P.EIGHT_BANKS || globalThis.EIGHT_BANKS;
// a JSON string literal is a valid C++ string literal; non-ASCII as \u escapes (MSVC-safe)
const esc = s => JSON.stringify(s).replace(/[\u0080-\uffff]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
const rows = [];
for (const b of banks) rows.push([`Bank: ${b.name}`, JSON.stringify({bank: b.bank, tempo: b.tempo || (b.bank && b.bank.tempo), swing: b.bank && b.bank.swing})]);
for (const k of kits) rows.push([`Kit: ${k.cat} / ${k.name}`, JSON.stringify({params: k.params})]);
let out = '// Generated by eight/tools/gen-plugin-presets.mjs from eight/presets.js. Do not edit.\n#pragma once\n';
out += 'namespace eight {\nstruct PluginPreset { const char* name; const char* json; };\n';
out += `static const PluginPreset PRESETS[] = {\n`;
for (const [n, j] of rows) out += `  {${esc(n.replace(/[^\x20-\x7e]/g, '-'))}, ${esc(j)}},\n`;
out += `};\nstatic const int kPresets = ${rows.length};\n}\n`;
writeFileSync(path.join(here, '../../plugins/eight/Presets.inc'), out);
console.log(`${rows.length} presets (${banks.length} banks, ${kits.length} kits)`);
