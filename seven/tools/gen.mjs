// Writes plugins/seven/Voices.inc (the 32 factory voices and the panel's group labels) from seven/voices.js.
// usage: node seven/tools/gen.mjs
import {createRequire} from 'module';
import fs from 'fs';
const require = createRequire(import.meta.url);
globalThis.DX = require('../engine.js');
const V = require('../voices.js');
const out = ['// Generated by seven/tools/gen.mjs from seven/voices.js: do not edit.', 'static const unsigned char FACTORY_VOICES[32][156] = {'];
for (const v of V.FACTORY) out.push('  {' + Array.from(v).join(',') + '},');
out.push('};', 'static const char* const VOICE_GROUPS[32] = {' + V.GROUPS.map(g => JSON.stringify(g)).join(', ') + '};', '');
fs.writeFileSync(new URL('../../plugins/seven/Voices.inc', import.meta.url), out.join('\n'));
console.log('wrote plugins/seven/Voices.inc');
