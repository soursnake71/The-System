// Writes plugins/dmx/Kits.inc from dmx/kits.js, so the plugin has the app's kits, factory patterns and MIDI note map.
// usage: node dmx/tools/gen.mjs
import { createRequire } from 'module';
import { writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
const here = dirname(fileURLToPath(import.meta.url)), require = createRequire(import.meta.url);
const K = require(join(here, '..', 'kits.js'));
const G = K.DMX_FADERS.map(f => f[0]);
const q = s => JSON.stringify(s);
let o = `// generated by dmx/tools/gen.mjs from dmx/kits.js: don't edit by hand
#pragma once
namespace dmx {
constexpr int kKits = ${K.DMX_KITS.length}, kMaxVoices = ${Math.max(...K.DMX_KITS.map(k => k.voices.length))}, kPatterns = ${K.DMX_PATTERNS.length}, kSteps = 16, kGroups = ${G.length};
static const char* const kGroupNames[kGroups] = {${K.DMX_FADERS.map(f => q(f[1])).join(', ')}};
struct VoiceDef { const char* file; const char* name; int group; bool open; };
struct KitDef { const char* id; const char* name; int voices; VoiceDef v[kMaxVoices]; };
static const KitDef kKitDefs[kKits] = {
${K.DMX_KITS.map(k => `  {${q(k.id)}, ${q(k.name)}, ${k.voices.length}, {${k.voices.map(v => `{${q(v[0])}, ${q(v[1])}, ${G.indexOf(v[2])}, ${K.dmxIsOpen(v)}}`).join(', ')}}}`).join(',\n')}};
static const char* const kPatternNames[kPatterns] = {${K.DMX_PATTERNS.map(p => q(p[0])).join(', ')}};
// factory[kit][pattern][voice] = 16 steps: '0' off, '1' hit, '2' accent
static const char* const kFactory[kKits][kPatterns][kMaxVoices] = {
${K.DMX_KITS.map(k => `  {${K.DMX_PATTERNS.map((_, pi) => '{' + K.dmxFactory(k, pi).rows.map(r => q(r.join(''))).join(', ') + '}').join(',\n   ')}}`).join(',\n')}};
// MIDI note -> voice (-1: none)
static const signed char kNoteVoice[kKits][128] = {
${K.DMX_KITS.map(k => '  {' + Array.from({length:128}, (_, n) => K.dmxNoteVoice(k, n)).join(',') + '}').join(',\n')}};
}
`;
writeFileSync(join(here, '..', '..', 'plugins', 'dmx', 'Kits.inc'), o);
console.log('wrote plugins/dmx/Kits.inc');
