// Writes plugins/dmx/Kits.inc from dmx/kits.js, so the plugin has the app's kits, factory patterns and MIDI note map.
// usage: node dmx/tools/gen.mjs
import { createRequire } from 'module';
import { writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
const here = dirname(fileURLToPath(import.meta.url)), require = createRequire(import.meta.url);
const K = require(join(here, '..', 'kits.js'));
const G = K.DMX_FADERS.map(f => f[0]);
const q = s => JSON.stringify(s);
let o = `// generated by dmx/tools/gen.mjs from dmx/kits.js: don't edit by hand
#pragma once
namespace dmx {
constexpr int kKits = ${K.DMX_KITS.length}, kMaxVoices = ${Math.max(...K.DMX_KITS.map(k => k.voices.length))}, kPatterns = ${K.DMX_PATTERNS.length}, kSteps = 16, kGroups = ${G.length};
static const char* const kGroupNames[kGroups] = {${K.DMX_FADERS.map(f => q(f[1])).join(', ')}};
struct VoiceDef { const char* file; const char* name; int group; bool open; };
struct KitDef { const char* id; const char* name; int voices; VoiceDef v[kMaxVoices]; };
static const KitDef kKitDefs[kKits] = {
${K.DMX_KITS.map(k => `  {${q(k.id)}, ${q(k.name)}, ${k.voices.length}, {${k.voices.map(v => `{${q(v[0])}, ${q(v[1])}, ${G.indexOf(v[2])}, ${K.dmxIsOpen(v)}}`).join(', ')}}}`).join(',\n')}};
static const char* const kPatternNames[kPatterns] = {${K.DMX_PATTERNS.map(p => q(p[0])).join(', ')}};
// factory[kit][pattern][voice] = 16 steps: '0' off, '1' hit, '2' accent
static const char* const kFactory[kKits][kPatterns][kMaxVoices] = {
${K.DMX_KITS.map(k => `  {${K.DMX_PATTERNS.map((_, pi) => '{' + K.dmxFactory(k, pi).rows.map(r => q(r.join(''))).join(', ') + '}').join(',\n   ')}}`).join(',\n')}};
// MIDI note -> voice (-1: none)
static const signed char kNoteVoice[kKits][128] = {
${K.DMX_KITS.map(k => '  {' + Array.from({length:128}, (_, n) => K.dmxNoteVoice(k, n)).join(',') + '}').join(',\n')}};
}
`;
writeFileSync(join(here, '..', '..', 'plugins', 'dmx', 'Kits.inc'), o);
console.log('wrote plugins/dmx/Kits.inc');

// plugins/dmx/Params.inc: the sound parameters (dmx/engine.js PARAMS), the 100 presets and the dice rules (dmx/presets.js)
{
  const E = require(join(here, '..', 'engine.js')), PR = require(join(here, '..', 'presets.js'));
  const num = x => { const s = String(+x.toPrecision(15)); return /[.e]/.test(s) ? s : s + '.0'; };
  const KINDS = ['lin', 'log', 'int', 'set', 'add', 'mul'];
  let o = `// generated by dmx/tools/gen.mjs from dmx/engine.js and dmx/presets.js: don't edit by hand
#pragma once
namespace dmx {
constexpr int kParams = ${E.PARAMS.length}, kNG = ${E.NG}, kNF = ${E.NF}, kCards = ${E.NC}, kRenderFields = ${E.RENDER_FIELDS};
struct ParamDef { const char* id; const char* name; double min, max, def; };
static const ParamDef kParamDefs[kParams] = {
${E.PARAMS.map(q => `  {${JSON.stringify(q[0])}, ${JSON.stringify(q[1])}, ${num(q[2])}, ${num(q[3])}, ${num(q[4])}}`).join(',\n')}};
static const char* const kCardIds[kCards] = {${E.CARD_IDS.map(x => JSON.stringify(x)).join(', ')}};
static const char* const kCardNames[kCards] = {${E.CARD_NAMES.map(x => JSON.stringify(x)).join(', ')}};
static const char* const kCardCircuit[kCards] = {${E.CARDS.map(x => JSON.stringify(x)).join(', ')}};
constexpr int kPresets = ${PR.PRESETS.length};
static const char* const kPresetNames[kPresets] = {${PR.PRESETS.map(p => JSON.stringify(p.name)).join(', ')}};
static const double kPresetValues[kPresets][kParams] = {
${PR.PRESETS.map(p => '  {' + p.p.map(num).join(',') + '}').join(',\n')}};
// the dice: per part, rules {param, kind (0 lin 1 log 2 int 3 set 4 add 5 mul), a, b, chance}, '*' already spread over the cards
struct DiceRule { int param, kind; double a, b, chance; };
constexpr int kDiceParts = ${PR.DICE_PARTS.length};
static const char* const kDicePartNames[kDiceParts] = {${PR.DICE_PARTS.map(x => JSON.stringify(x)).join(', ')}};
`;
  const ids = id => id.includes('*') ? E.CARD_IDS.map(v => id.replace('*', v)) : id.split(',');
  const parts = Object.keys(PR.DICE);
  // a rule keeps its '*' groups together: the rng draws in the same order as presets.js (per expanded param: chance, then value)
  parts.forEach((name, pi) => {
    o += `static const DiceRule kDice${pi}[] = {\n` + PR.DICE[name].map(([id, kind, a, b, chance = 1]) => ids(id).map(k => `{${E.P[k]}, ${KINDS.indexOf(kind)}, ${num(a)}, ${num(b === undefined ? 0 : b)}, ${num(chance)}}`).join(', ')).join(',\n') + '};\n';
  });
  o += `static const DiceRule* const kDiceRules[${parts.length}] = {${parts.map((_, i) => `kDice${i}`).join(', ')}};
static const int kDiceCounts[${parts.length}] = {${parts.map(n => PR.DICE[n].reduce((s, r) => s + ids(r[0]).length, 0)).join(', ')}};
}
`;
  writeFileSync(join(here, '..', '..', 'plugins', 'dmx', 'Params.inc'), o);
  console.log('wrote plugins/dmx/Params.inc');
}
