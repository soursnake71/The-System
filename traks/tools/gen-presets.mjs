// Writes the 100 factory presets and the dice rules into the plugin (plugins/traks/Presets.inc), and plays every
// preset to check it sounds (not silent, not clipping hard).
// usage: node traks/tools/gen-presets.mjs [--check]   (--check: fail if Presets.inc is out of date)
import {createRequire} from 'module';
import fs from 'fs';
const req = createRequire(import.meta.url);
const D = req('../engine.js'), M = req('../machine.js'), PR = req('../presets.js');
const rom = D.parseRom(new Uint8Array(fs.readFileSync(new URL('../rom/traks.rom', import.meta.url))));
const out = new URL('../../plugins/traks/Presets.inc', import.meta.url).pathname;
const num = v => Number.isInteger(v) ? String(v) : String(+v.toFixed(4));
let s = '// Generated by traks/tools/gen-presets.mjs from traks/presets.js. Do not edit.\n';
s += `constexpr int kPresets = ${PR.PRESETS.length};\nstruct Preset { const char* name; double p[NP]; };\n`;
s += 'inline const Preset PRESETS[kPresets] = {\n';
for (const pr of PR.PRESETS) s += `  {"${pr.name.replace(/"/g, '\\"').replace('·', '\\xc2\\xb7')}", {${pr.p.map(num).join(',')}}},\n`;
s += '};\n';
// dice rules: {part, id, kind, a, b, chance}; kind 0 lin 1 log 2 int 3 set 4 add 5 mul
const K = {lin:0, log:1, int:2, set:3, add:4, mul:5};
s += 'struct DiceRule { int part; const char* id; int kind; double a, b, chance; };\n';
s += `inline const char* const DICE_PARTS[${PR.DICE_PARTS.length}] = {${PR.DICE_PARTS.map(x => `"${x}"`).join(', ')}};\n`;
const rules = [];
Object.keys(PR.DICE).forEach(part => PR.DICE[part].forEach(([id, k, a, b, c = 1]) => rules.push(`  {${PR.DICE_PARTS.indexOf(part)}, "${id}", ${K[k]}, ${num(a)}, ${num(b ?? 0)}, ${num(c)}}`)));
s += `constexpr int kDiceRules = ${rules.length};\ninline const DiceRule DICE_RULES[kDiceRules] = {\n${rules.join(',\n')}\n};\n`;
if (process.argv.includes('--check')){
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== s){ console.log('FAIL plugins/traks/Presets.inc is out of date: run node traks/tools/gen-presets.mjs'); process.exit(1); }
  console.log('ok   Presets.inc matches presets.js');
} else { fs.writeFileSync(out, s); console.log('wrote', out, PR.PRESETS.length, 'presets'); }
// play each preset: song 00 (the factory demo)
let bad = 0;
const sr = 32000, n = sr * 4;
for (const pr of PR.PRESETS){
  const e = new D.Engine(sr); rom.forEach((r, v) => e.setRom(v, r.codes, r.rate)); e.setAll(pr.p);
  const q = new M.Machine(e, sr); q.group = 1; q.bpm = 120; q.start();
  const L = new Float64Array(n), R = new Float64Array(n); for (let o = 0; o < n; o += 256) q.render(L, R, o, Math.min(256, n - o));
  let pk = 0, rms = 0, nan = false; for (let i = 0; i < n; i++){ const x = Math.abs(L[i]) + 0, y = Math.abs(R[i]); if (!isFinite(x) || !isFinite(y)) nan = true; pk = Math.max(pk, x, y); rms += L[i] * L[i] + R[i] * R[i]; }
  rms = Math.sqrt(rms / (2 * n));
  const ok = !nan && rms > 0.02 && rms < 0.6;
  if (!ok){ bad++; console.log(`FAIL ${pr.name}: rms ${rms.toFixed(3)} peak ${pk.toFixed(3)}${nan ? ' NaN' : ''}`); }
}
console.log(bad ? `${bad} presets failed` : `ok   all ${PR.PRESETS.length} presets play`);
process.exitCode = bad ? 1 : 0;
