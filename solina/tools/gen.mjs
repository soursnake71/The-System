// Writes plugins/solina/Params.inc and Presets.inc from solina/engine.js and solina/presets.js, so the plugin and the
// app share one parameter list and one preset list.  node solina/tools/gen.mjs
import {createRequire} from 'module';
import {writeFileSync} from 'fs';
import {dirname, join} from 'path';
import {fileURLToPath} from 'url';
const here = dirname(fileURLToPath(import.meta.url)), root = join(here, '..', '..'), req = createRequire(import.meta.url);
const D = req(join(root, 'solina', 'engine.js')), PRE = req(join(root, 'solina', 'presets.js'));
const q = s => JSON.stringify(s), num = v => Number.isInteger(v) ? v.toFixed(1) : String(v);
let a = '// generated by solina/tools/gen.mjs from solina/engine.js; do not edit\n';
a += `namespace pid { enum : int { ${D.PARAMS.map(p => p.id).join(', ')}, count }; }\n`;
a += 'static const ParamInfo PARAMS[] = {\n' + D.PARAMS.map(p => `  {${q(p.id)}, ${q(p.name)}, ${num(p.min)}, ${num(p.max)}, ${num(p.def)}, ${num(p.step)}, ${q(p.unit)}, ${q(p.group)}, ${p.cc}, {${p.choices.map(q).join(', ')}}}`).join(',\n') + '\n};\n';
writeFileSync(join(root, 'plugins', 'solina', 'Params.inc'), a);
let b = '// generated by solina/tools/gen.mjs from solina/presets.js; do not edit\n';
b += `static constexpr int kPresets = ${PRE.length};\nstruct PresetInfo { const char* name; double v[pid::count]; };\nstatic const PresetInfo PRESETS[] = {\n`;
b += PRE.map(pr => { const v = Object.assign(D.defaults(), pr.p); return `  {${q(pr.name)}, {${D.PARAMS.map(p => num(v[p.id])).join(', ')}}}`; }).join(',\n') + '\n};\n';
writeFileSync(join(root, 'plugins', 'solina', 'Presets.inc'), b);
console.log(D.PARAMS.length, 'parameters,', PRE.length, 'presets');
