// Writes the 100 factory presets and the dice rules (plugins/linn/Presets.inc) and the factory memory (the grooves 11-57
// and the demo song: plugins/linn/Factory.inc) into the plugin, and plays every preset to check it sounds (not silent,
// not clipping hard).
// usage: node linn/tools/gen-presets.mjs [--check]   (--check: fail if the .inc files are out of date)
import {createRequire} from 'module';
import fs from 'fs';
const req = createRequire(import.meta.url);
const D = req('../engine.js'), M = req('../machine.js'), PR = req('../presets.js');
const rom = D.parseRom(new Uint8Array(fs.readFileSync(new URL('../rom/linn.rom', import.meta.url))));
const outP = new URL('../../plugins/linn/Presets.inc', import.meta.url).pathname, outF = new URL('../../plugins/linn/Factory.inc', import.meta.url).pathname;
const num = v => Number.isInteger(v) ? String(v) : String(+v.toFixed(4));
let s = '// Generated by linn/tools/gen-presets.mjs from linn/presets.js. Do not edit.\n';
s += `constexpr int kPresets = ${PR.PRESETS.length};\nstruct Preset { const char* name; double p[NP]; };\n`;
s += 'inline const Preset PRESETS[kPresets] = {\n';
for (const pr of PR.PRESETS) s += `  {"${pr.name.replace(/"/g, '\\"').replace('·', '\\xc2\\xb7')}", {${pr.p.map(num).join(',')}}},\n`;
s += '};\n';
const K = {lin:0, log:1, int:2, set:3, add:4, mul:5};
s += 'struct DiceRule { int part; const char* id; int kind; double a, b, chance; };\n';
s += `inline const char* const DICE_PARTS[${PR.DICE_PARTS.length}] = {${PR.DICE_PARTS.map(x => `"${x}"`).join(', ')}};\n`;
const rules = [];
Object.keys(PR.DICE).forEach(part => PR.DICE[part].forEach(([id, k, a, b, c = 1]) => rules.push(`  {${PR.DICE_PARTS.indexOf(part)}, "${id}", ${K[k]}, ${num(a)}, ${num(b ?? 0)}, ${num(c)}}`)));
s += `constexpr int kDiceRules = ${rules.length};\ninline const DiceRule DICE_RULES[kDiceRules] = {\n${rules.join(',\n')}\n};\n`;
// the factory memory
const mem = M.defaultMemory(), fp = mem.pats.slice(0, M.FACTORY.length);
let f = '// Generated by linn/tools/gen-presets.mjs from linn/machine.js (FACTORY, defaultMemory). Do not edit.\n';
f += `constexpr int kFactoryPats = ${fp.length};\nstruct FactoryPat { int len, ec, tim, at, n; };\n`;
let at = 0; const rows = [], evs = [];
for (const p of fp){ rows.push(`{${p.len}, ${p.ec}, ${p.tim}, ${at}, ${p.ev.length}}`); for (const x of p.ev) evs.push(`{${x.t},${x.s}}`); at += p.ev.length; }
f += `inline const FactoryPat FACTORY_PATS[kFactoryPats] = {${rows.join(', ')}};\n`;
f += `inline const int FACTORY_EV[${evs.length}][2] = {${evs.join(',')}};\n`;
f += `constexpr int kDemoSteps = ${mem.songs[0].steps.length};\ninline const int DEMO_SONG[kDemoSteps] = {${mem.songs[0].steps.join(', ')}};\n`;
if (process.argv.includes('--check')){
  let bad = false;
  for (const [o, t] of [[outP, s], [outF, f]]){ const cur = fs.existsSync(o) ? fs.readFileSync(o, 'utf8') : ''; if (cur !== t){ console.log('FAIL ' + o + ' is out of date: run node linn/tools/gen-presets.mjs'); bad = true; } }
  if (bad) process.exit(1);
  console.log('ok   Presets.inc and Factory.inc match presets.js / machine.js');
} else { fs.writeFileSync(outP, s); fs.writeFileSync(outF, f); console.log('wrote', outP, PR.PRESETS.length, 'presets, and', outF); }
// play each preset: song 11 (the factory demo)
let bad = 0;
const sr = 32000, n = sr * 4;
for (const pr of PR.PRESETS){
  const e = new D.Engine(sr); rom.forEach((L, g) => e.setGroup(g, L)); e.setAll(pr.p);
  const q = new M.Machine(e, sr); q.mode = 1; q.bpm = 120; q.start(false, 0);
  const L = new Float64Array(n), R = new Float64Array(n); for (let o = 0; o < n; o += 256) q.render(L, R, o, Math.min(256, n - o));
  let pk = 0, rms = 0, nan = false; for (let i = 0; i < n; i++){ const x = Math.abs(L[i]), y = Math.abs(R[i]); if (!isFinite(x) || !isFinite(y)) nan = true; pk = Math.max(pk, x, y); rms += L[i] * L[i] + R[i] * R[i]; }
  rms = Math.sqrt(rms / (2 * n));
  const ok = !nan && rms > 0.015 && rms < 0.6;
  if (!ok){ bad++; console.log(`FAIL ${pr.name}: rms ${rms.toFixed(3)} peak ${pk.toFixed(3)}${nan ? ' NaN' : ''}`); }
}
console.log(bad ? `${bad} presets failed` : `ok   all ${PR.PRESETS.length} presets play`);
process.exitCode = bad ? 1 : 0;
