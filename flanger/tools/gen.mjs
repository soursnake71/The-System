// Writes plugins/flanger/Presets.inc from flanger/presets.json (the one list of presets the app and plugin share).
// usage: node flanger/tools/gen.mjs
import fs from 'fs';
import {createRequire} from 'module';
const M = createRequire(import.meta.url)('../engine.js');
const presets = JSON.parse(fs.readFileSync(new URL('../presets.json', import.meta.url)));
const q = s => JSON.stringify(s);
let out = '// Generated by flanger/tools/gen.mjs from flanger/presets.json. Do not edit.\n';
out += '// {name, description, {manual, width, speed, regen, bypass, mix, spread, level}}\n';
for (const p of presets){
  const v = Object.assign(M.defaults(), p.values);
  out += `{${q(p.name)}, ${q(p.desc)}, {${M.PARAMS.map(x => v[x.id]).join(', ')}}},\n`;
}
fs.writeFileSync(new URL('../../plugins/flanger/Presets.inc', import.meta.url), out);
console.log(presets.length + ' presets');
