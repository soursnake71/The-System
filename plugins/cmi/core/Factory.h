inline const char* factoryNote(const std::string& name) {
    static const std::map<std::string, const char*> m = {
        { "ORCH5", "the orchestra hit" }, { "ORCH2", "orchestra hit" }, { "ARR1", "the breathy 'aah' choir" }, { "SARARR1", "choir" },
        { "KICK1", "Page R kick" }, { "SNARE1", "Page R snare" }, { "CROSSTIX", "Page R cross-stick" }, { "HIHAT2", "Page R hi-hat" },
        { "HHOPEN1", "Page R open hi-hat" }, { "CLAP", "hand clap" }, { "BASSGT", "bass guitar" },
    };
    auto it = m.find(name); return it == m.end() ? "" : it->second;
}

// where a preset is in your library: what you chose for it ("NAME@DISK"), else the voice on its own disk (by the
// disk's label or file / folder name), else the same name anywhere. -1: not in your library.
inline int findFactory(const Catalog& cat, int n, const std::string& chosen = "") {
    const auto& ps = factoryPresets();
    if (!chosen.empty()) {
        const size_t at = chosen.find('@');
        const int i = cat.find(chosen.substr(0, at), at == std::string::npos ? "" : chosen.substr(at + 1));
        if (i >= 0) return i;
    }
    if (n < 0 || n >= (int) ps.size()) return -1;
    const FactoryPreset& p = ps[(size_t) n];
    auto exact = [&](const char* disk) { for (size_t i = 0; i < cat.voices.size(); ++i) if (cat.voices[i].name == p.name && cat.voices[i].disk == disk) return (int) i; return -1; };
    int i = exact(p.disk); if (i >= 0) return i;
    i = exact(p.file); if (i >= 0) return i;
    return cat.find(p.name);
}

// the first preset of each disk: for jumping to a disk
inline std::vector<std::pair<std::string, int>> factoryDisks() {
    std::vector<std::pair<std::string, int>> d; const auto& ps = factoryPresets();
    for (int i = 0; i < (int) ps.size(); ++i) if (d.empty() || d.back().first != ps[(size_t) i].file) d.push_back({ ps[(size_t) i].file, i });
    return d;
}

