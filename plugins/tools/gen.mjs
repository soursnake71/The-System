// Writes plugins/gen/tables.inc from the web app's own parameter tables (see extract.mjs).
// Run: node plugins/tools/gen.mjs
import fs from 'fs'; import path from 'path'; import {execFileSync} from 'child_process'; import {fileURLToPath} from 'url';
const here = path.dirname(fileURLToPath(import.meta.url)), root = path.resolve(here, '../..');
process.chdir(root);
const T = JSON.parse(execFileSync('node', ['plugins/tools/extract.mjs', 'index.html'], {maxBuffer:1 << 26}).toString());
const q = s => JSON.stringify(String(s)).replace(/−/g, '-').replace(/[^\x20-\x7e]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
const num = v => { const s = String(+v); return /[.e]/.test(s) ? s : s + '.0'; };
let o = '// Generated by plugins/tools/gen.mjs from index.html. Do not edit by hand.\n#pragma once\n#include "../common/Spec.h"\nnamespace omega::gen {\n';
const choiceVal = (opts, v) => { const numeric = opts.every(x => typeof x.v === 'number'); return numeric ? +v : opts.findIndex(x => x.v === v); };
for (const [k, U] of Object.entries(T.rack)){
  o += `inline void rack_${k}(Spec& s){\n  s.name = ${q(U.name)}; s.sub = ${q(U.sub)};\n`;
  for (const m of U.menus){ const numeric = m.opts.every(x => typeof x.v === 'number');
    o += `  s.choice(${q(m.key)}, ${q(m.label)}, {${m.opts.map(x => `{${q(x.l)}, ${numeric ? num(x.v) : num(m.opts.indexOf(x))}}`).join(', ')}}, ${Math.max(0, m.opts.findIndex(x => x.v === m.def))});\n`; }
  for (const p of U.knobs) o += `  s.knob(${q(p.key)}, ${q(p.label)}, ${num(p.min)}, ${num(p.max)}, ${num(p.step)}, ${num(p.def)}, Fmt::${p.fmt});\n`;
  for (const [n, P] of Object.entries(U.presets)){
    const kv = Object.entries(P).map(([key, v]) => { const m = U.menus.find(x => x.key === key); return `{${q(key)}, ${num(m ? (m.opts.every(x => typeof x.v === 'number') ? v : m.opts.findIndex(x => x.v === v)) : v)}}`; });
    o += `  s.preset(${q(n)}, {${kv.join(', ')}});\n`; }
  o += '}\n';
}
// Prophet-5: knobs 0..1 (7-bit CVs inside), switches on/off
const P = T.p5, over = {oApw:'pw', oBpw:'pw', cut:'cutoff', res:'res10', lfoF:'p5lfo', wmMix:'wmmix', oBf:'st', oAf:'st'};
o += 'inline void prophet5(Spec& s){\n';
for (const k of P.knobs) o += `  s.knob(${q(k.key)}, ${q(k.sec + ': ' + k.label)}, 0.0, 1.0, 0.0, ${num(P.init[k.key] ?? 0)}, Fmt::${over[k.key] || k.fmt});\n`;
for (const k of P.switches) o += `  s.toggle(${q(k.key)}, ${q(k.sec + ': ' + k.label)}, ${P.init[k.key] ? 'true' : 'false'});\n`;
o += `  s.knob("wheel", "Mod wheel", 0.0, 1.0, 0.0, ${num(P.init.wheel || 0)}, Fmt::pct);\n`;
for (const [n, pr] of Object.entries(P.presets)){ const all = Object.assign({}, P.init, pr); o += `  s.preset(${q(n)}, {${Object.entries(all).map(([key, v]) => `{${q(key)}, ${num(v)}}`).join(', ')}});\n`; }
o += '}\n}\n';
fs.mkdirSync('plugins/gen', {recursive:true}); fs.writeFileSync('plugins/gen/tables.inc', o); console.log('wrote plugins/gen/tables.inc', o.length, 'bytes');
